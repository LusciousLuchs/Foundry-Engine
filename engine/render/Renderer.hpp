#pragma once
// Vulkan renderer with raylib-like immediate semantics, executed as an ordered command list.
//
//   * One vertex format for everything (raylib's attribute order: position, texcoord, normal, colour).
//   * Built-in draws (lit 3D triangles, unlit lines, 2D) are batched; consecutive draws with the same
//     state merge into one command.
//   * Ported custom shaders (see tools/shaders.py) draw with their own uniforms, snapshotted per draw.
//   * State (depth test/write, back-face culling, blending, scissor) applies to subsequent draws,
//     like rlgl. Pipelines are created on demand and cached.
//   * Matrices follow raylib/OpenGL conventions; clip space is converted to Vulkan internally.
//
// Built-in lighting: sun + hemisphere ambient + 8 point lights, Blinn-Phong, ACES, sun shadow map.
#include "platform/Window.hpp"
#include "rhi/vulkan/VkContext.hpp"
#include <cstdint>
#include <string>
#include <unordered_map>
#include <vector>

namespace foundry::render {

struct Vertex {                      // 36 bytes; attribute locations 0..3 match raylib
    float x, y, z;
    float u, v;
    float nx, ny, nz;
    uint8_t r, g, b, a;
};
using Vertex3D = Vertex;             // (zero normal = unlit)
struct Vertex2D { float x, y; uint8_t r, g, b, a; };

enum class Blend : uint8_t { Off, Alpha, Additive, Multiplied };
enum class Topo : uint8_t { Triangles, Lines };
constexpr int kMaxPointLights = 8;

// Precompiled shader (generated by tools/shaders.py).
struct ShaderUniformInfo { const char* name; uint8_t type; uint16_t count; uint32_t offset; };
struct PortedShader {
    const char* name;
    uint64_t vsHash, fsHash;
    const uint32_t* vs; size_t vsBytes;
    const uint32_t* fs; size_t fsBytes;
    const ShaderUniformInfo* uniforms; int nUniforms;
    uint32_t blockSize;
};
const PortedShader* findPortedShader(const char* vsSource, const char* fsSource);   // nullptr sources = default
const PortedShader* findPortedShaderByName(const char* name);                       // e.g. "builtin_default"

// Standard per-draw uniforms (raylib/GL convention matrices, column-major as raylib stores them).
struct StdUniforms {
    float mvp[16], model[16], normal[16], view[16], proj[16];
    float diffuse[4];
};

class Renderer {
public:
    ~Renderer() { shutdown(); }
    bool init(platform::Window& win);
    void shutdown();

    bool beginFrame(float r, float g, float b, float a);   // false: skip this frame
    void endFrame();
    void setClear(float r, float g, float b, float a) { clear_[0] = r; clear_[1] = g; clear_[2] = b; clear_[3] = a; }

    // ---- built-in 3D (world-space vertices) ----
    // overlay = no depth test/write (editor gizmos). viewProj is column-major as raylib stores it.
    void begin3D(const float viewProj[16], float camX, float camY, float camZ, bool overlay = false);
    void end3D();
    void tri(const Vertex& a, const Vertex& b, const Vertex& c);
    void line(const Vertex& a, const Vertex& b);
    void tri2D(const Vertex2D& a, const Vertex2D& b, const Vertex2D& c);   // pixels, origin top-left

    // ---- render state (applies to following draws) ----
    void setDepthTest(bool on) { st_.depthTest = on; }
    void setDepthWrite(bool on) { st_.depthWrite = on; }
    void setCullBack(bool on) { st_.cullBack = on; }
    void setBlend(Blend b) { st_.blend = b; }
    void setScissor(bool on, int x, int y, int w, int h) { st_.scissorOn = on; st_.sc[0] = x; st_.sc[1] = y; st_.sc[2] = w; st_.sc[3] = h; }

    // ---- custom shaders and textures ----
    int createShader(const PortedShader& s);                    // id > 0, 0 on failure
    void destroyShader(int id);
    uint8_t* shaderBlock(int id);                               // CPU copy of the uniform block (SetShaderValue writes here)
    int uniformIndex(int id, const char* name) const;           // -1 if the shader has no such uniform
    const ShaderUniformInfo* uniformInfo(int id, int index) const;
    int createTexture(int w, int h, const void* rgba8, bool mipmaps);   // id > 0 (id 1 is a built-in white pixel)
    void destroyTexture(int id);
    void generateMipmaps(int id);
    void setTextureFilter(int id, int filter);                  // raylib TEXTURE_FILTER_*
    void setTextureWrap(int id, int wrap);                      // raylib TEXTURE_WRAP_*
    // ---- GPU-resident meshes (vertices stay on the GPU between frames) ----
    // Static meshes live in device-local memory; dynamic ones keep one host-visible copy per frame in flight.
    int createMesh(const Vertex* v, uint32_t n, bool dynamic);                      // id > 0
    void updateMeshAttribute(int id, int attrib, const void* data, size_t bytes, size_t byteOffset);   // raylib attrib: 0 pos, 1 uv, 2 normal, 3 colour
    void destroyMesh(int id);                                                       // freed once the GPU is done with it
    void drawCustomMesh(int shader, int mesh, Topo topo, const StdUniforms& u, int texture);
    // Draw with a ported shader. Vertices are in the space the shader expects (mesh-local for 3D,
    // pixels for 2D); matrices come in `u`. texture 0 = white.
    void drawCustom(int shader, const Vertex* v, uint32_t n, Topo topo, const StdUniforms& u, int texture);

    // ---- lighting for the built-in lit shader ----
    void setSun(float dx, float dy, float dz, float r, float g, float b, float intensity);
    void setAmbient(const float sky[3], const float ground[3]);
    bool addPointLight(float x, float y, float z, float range, float r, float g, float b, float intensity);
    void setShadows(bool enabled, float cx, float cy, float cz, float radius) {
        shadowOn_ = enabled; shadowC_[0] = cx; shadowC_[1] = cy; shadowC_[2] = cz; shadowR_ = radius;
    }
    void setShadowsEnabled(bool on) { shadowOn_ = on; }
    bool shadowsEnabled() const { return shadowOn_; }

    void requestScreenshot(const std::string& path) { shotPath_ = path; }
    int width() const { return int(frame_.extent.width); }
    int height() const { return int(frame_.extent.height); }
    bool inFrame() const { return inFrame_; }
    rhi::vk::Context& context() { return ctx_; }
    uint32_t droppedVertices() const { return dropped_; }

private:
    struct State {
        bool depthTest = false, depthWrite = true, cullBack = true, scissorOn = false;   // raylib defaults (depth test is on only inside begin3D)
        Blend blend = Blend::Alpha;
        int sc[4]{0, 0, 0, 0};
    };
    enum Kind : uint8_t { kLit = 0, kUi = 1, kCustom = 2 };
    struct Cmd {
        Kind kind; Topo topo; State st;
        bool overlay = false;
        int shader = 0, segment = -1, texture = 0, mesh = 0;
        uint32_t first = 0, count = 0, uboOffset = 0;
    };
    struct Shader {
        VkShaderModule vs = nullptr, fs = nullptr;
        const PortedShader* src = nullptr;
        std::vector<uint8_t> block;
        int offMvp = -1, offModel = -1, offNormal = -1, offView = -1, offProj = -1, offDiffuse = -1, offScreen = -1;
    };
    struct Texture {
        rhi::vk::Image img;
        VkSampler sampler = nullptr;
        VkDescriptorSet set = nullptr;
        int w = 0, h = 0, mips = 1, filter = 1, wrap = 0;
        bool used = false, useMips = false;
    };
    struct GpuMesh {
        rhi::vk::Buffer buf[rhi::vk::kFramesInFlight];
        std::vector<Vertex> cpu;     // packed copy (dynamic meshes only)
        uint32_t count = 0;
        bool dynamic = false, used = false;
        bool dirty[rhi::vk::kFramesInFlight]{};
    };
    struct FrameRes { rhi::vk::Buffer verts, ubo, lights; VkDescriptorSet lightSet = nullptr, dynSet = nullptr; };

    bool createPipelineLayouts();
    VkPipeline getPipeline(const Cmd& c);
    VkPipeline buildPipeline(const Cmd& c);
    bool makeSampler(Texture& t);
    void pushCmd(const Cmd& c);
    Vertex* reserve(uint32_t n);
    bool sameBatch(const Cmd& a, const Cmd& b) const;
    State drawState() const;

    platform::Window* win_ = nullptr;
    rhi::vk::Context ctx_;
    rhi::vk::Frame frame_;
    FrameRes res_[rhi::vk::kFramesInFlight];
    VkDescriptorSetLayout lightLayout_ = nullptr, dynLayout_ = nullptr, texLayout_ = nullptr;
    VkDescriptorPool lightPool_ = nullptr, dynPool_ = nullptr, texPool_ = nullptr;
    VkPipelineLayout litLayout_ = nullptr, uiLayout_ = nullptr, customLayout_ = nullptr, shadowLayout_ = nullptr;
    VkShaderModule mods_[5]{};      // lit.vert lit.frag ui.vert ui.frag shadow.vert
    VkPipeline shadowPipe_ = nullptr;
    std::unordered_map<uint64_t, VkPipeline> pipes_;
    rhi::vk::Image shadow_;
    VkSampler shadowSampler_ = nullptr;
    std::vector<Shader> shaders_;   // id - 1
    std::vector<Texture> textures_; // id - 1
    std::vector<GpuMesh> meshes_;   // id - 1
    std::vector<rhi::vk::Buffer> dead_[rhi::vk::kFramesInFlight];   // buffers waiting for their frame slot to retire
    uint32_t snapshotUniforms(int shader, const StdUniforms& u);

    bool inFrame_ = false, overlay_ = false;
    float clear_[4]{};
    int slot_ = 0, curSeg_ = -1;
    uint32_t nVerts_ = 0, maxVerts_ = 0, uboUsed_ = 0, uboSize_ = 0, dropped_ = 0;
    State st_;
    std::vector<Cmd> cmds_;
    std::vector<std::vector<float>> segs_;      // 20 floats each: viewProj + camPos
    std::string shotPath_;

    bool shadowOn_ = true;
    float shadowC_[3] = {0, 0, 0};
    float shadowR_ = 16.0f;
    struct LightsUBO {
        float sunDir[4], sunColor[4], ambSky[4], ambGround[4], counts[4];
        float shadowVP[16], shadowParams[4];
        float pts[kMaxPointLights][8];
    } lights_{};
    int nPoint_ = 0;
};

} // namespace foundry::render
