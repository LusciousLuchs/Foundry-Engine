#!/usr/bin/env python3
"""Generates engine/render/FontData.inc: a 1-bit monospace bitmap font (ASCII 32..126)
rasterised from DejaVu Sans Mono (free licence, see licenses/DejaVu-LICENSE.txt).
Usage: tools/gen_font.py [size]   (default 12)"""
import sys
from PIL import Image, ImageDraw, ImageFont
size = int(sys.argv[1]) if len(sys.argv) > 1 else 12
font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", size)
asc, desc = font.getmetrics()
W = int(round(font.getlength("M")))
H = asc + desc
rows = []
for c in range(32, 127):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
    px = im.load()
    rows.append([sum(1 << (W - 1 - x) for x in range(W) if px[x, y] >= 110) for y in range(H)])
with open("engine/render/FontData.inc", "w") as f:
    f.write("// Generated by tools/gen_font.py from DejaVu Sans Mono (see licenses/DejaVu-LICENSE.txt). Do not edit.\n")
    f.write(f"constexpr int kFontW = {W}, kFontH = {H};\n")
    f.write("// Per glyph (ASCII 32..126): kFontH rows, bit (kFontW-1-x) = pixel x.\n")
    f.write("constexpr unsigned short kFontRows[95][kFontH] = {\n")
    for r in rows:
        f.write("  {" + ",".join(str(v) for v in r) + "},\n")
    f.write("};\n")
print("cell", W, "x", H)
