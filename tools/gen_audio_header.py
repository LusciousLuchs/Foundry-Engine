#!/usr/bin/env python3
"""Regenerates engine/compat/audio.hpp from raylib.h's audio section.
Usage: tools/gen_audio_header.py <path to raylib.h>"""
import re, sys
t = open(sys.argv[1]).read()
sec = t[t.index("// Audio device management functions"):]
protos = re.findall(r'RLAPI\s+(.*?);', sec)
out = ['// Generated by tools/gen_audio_header.py from raylib.h. Do not edit.',
'// raylib\'s audio module (raudio.c) is compiled as C when FOUNDRY_RAYLIB_DIR is set; these are its entry points.',
'#pragma once', '#include "compat/raylib.hpp"', '',
'namespace foundry::compat {',
'struct rAudioBuffer; struct rAudioProcessor;',
'struct Wave { unsigned frameCount, sampleRate, sampleSize, channels; void* data; };',
'struct AudioStream { rAudioBuffer* buffer; rAudioProcessor* processor; unsigned sampleRate, sampleSize, channels; };',
'struct Sound { AudioStream stream; unsigned frameCount; };',
'struct Music { AudioStream stream; unsigned frameCount; bool looping; int ctxType; void* ctxData; };',
'using AudioCallback = void (*)(void* bufferData, unsigned frames);',
'} // namespace foundry::compat', '',
'// C linkage, global scope (as in raylib): the definitions live in raudio.c.', 'extern "C" {']
for p in protos:
    p = re.sub(r'\bunsigned int\b', 'unsigned', p)
    for ty in ('Wave', 'Sound', 'Music', 'AudioStream', 'AudioCallback'):
        p = re.sub(r'(?<![\w:])' + ty + r'(?![\w])', 'foundry::compat::' + ty, p)
    out.append('    ' + p + ';')
out.append('}')
open('engine/compat/audio.hpp', 'w').write("\n".join(out) + "\n")
